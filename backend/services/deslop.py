"""
去AI味确定性扫描器（Validator 层）
==================================
移植自 oh-story-claudecode 的 story-deslop 方法论（materials/deslop参考/）。

核心信念：AI味不是语法错误，而是过度圆滑、工整、解释充分。
处理策略（遵循"改最少、效果最大"+"替换不复用"原则）：
- 安全修复：只做"删了不丢剧情信息"的确定性删除（如"，带着……"万能状语）。
  上下文相关的改写（眼中闪过一丝→具体动作）交给 Writer 模板预防，不在此硬改，
  避免机械替换产生新的模板指纹。
- 检测计数：对其余毒句式只统计不改动，供监控模板预防效果。
"""
import re

# ---------------------------------------------------------------------------
# 毒句式检测（只计数，不改动）——来自 banned-words.md 的高危句式
# ---------------------------------------------------------------------------
TOXIC_PATTERNS = {
    # ★★★★★ 最毒："不是A，（而）是B"（如"眼睛里喷出的不是泪，是火"）
    "不是A而是B": re.compile(r"不是[^，。！？\n]{0,15}[，。]?\s*(?:而)?是"),
    # ★★★★ "，带着……"万能状语（如"他笑了一下，带着一丝嘲讽"）
    "带着状语": re.compile(r"，带着[^，。！？\n]{0,20}"),
    # ★★★★ 无情绪声线（如"声音不大，却带着不容置疑的力量"）
    "无情绪声线": re.compile(r"声音不大|语气毫无波澜|平静无波|听不出情绪"),
    # ★★★★ "他/她知道……"（告诉而非展示）
    "他知道": re.compile(r"(?:他|她|我)(?:知道|明白|意识到|清楚)"),
    # ★★★ 文言比喻词堆叠
    "比喻词": re.compile(r"仿佛|犹如|宛若|如同"),
    # ★★★ 神态模板（如"眼中闪过一丝""嘴角勾起一抹""心中涌起一股"）
    "神态模板": re.compile(r"眼中闪过|嘴角勾起|心中涌起|心头一震|瞳孔微缩|指节泛白|眉头微皱"),
    # ★★★ 抽象命运/收束腔（如"命运露出獠牙""反击才刚刚开始"）
    "收束腔": re.compile(r"这一刻|终于明白|这才意识到|才刚刚开始|命运(?:终于|的)"),
    # ★★  filler 动作（如"深吸一口气""不禁"）
    "filler动作": re.compile(r"深吸一口气|不禁"),
}

# ---------------------------------------------------------------------------
# 安全修复（确定性删除，删了不丢剧情信息）
# ---------------------------------------------------------------------------
# "，带着……"万能状语：删掉状语保留主句（"他笑了一下，带着一丝嘲讽"→"他笑了一下"）。
# 兼容"，却带着/还带着/又带着"（转折副词一并删除）。
# 只删短的（≤20字）且后接标点/行尾的，避免误删承担语义的长定语。
_SAFE_FIXES = [
    (re.compile(r"，(?:却|还|又|竟|正)?带着[^，。！？\n]{0,20}(?=[，。！？\n]|$)"), ""),
]


def analyze(text: str) -> dict:
    """统计各毒句式命中数（监控用，不改动文本）。"""
    return {name: len(pat.findall(text)) for name, pat in TOXIC_PATTERNS.items()}


def deslop(text: str) -> str:
    """去AI味确定性修复：只应用安全删除，返回清理后的文本。"""
    for pat, repl in _SAFE_FIXES:
        text = pat.sub(repl, text)
    return text
