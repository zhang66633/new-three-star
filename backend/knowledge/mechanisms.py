def get_relevant_mechanisms(scene_name: str, skeleton: str) -> list[str]:
    """根据场景内容返回相关机制。"""
    mechs = list(AXIOMS[:3])

    for keyword, rule in SOCIAL_RULES.items():
        if keyword in scene_name or keyword in skeleton:
            mechs.append(rule)

    return mechs[:5]


def get_relevant_bugs(scene_name: str, skeleton: str) -> list[str]:
    """根据场景内容返回可能出现的AI缺陷。"""
    bugs = []
    for category, items in BUGS.items():
        for item in items:
            for word in ["时间", "空间", "角色", "世界", "行军", "密谋", "宴会"]:
                if word in scene_name or word in skeleton[:200]:
                    if item not in bugs:
                        bugs.append(item)
    return bugs[:3]