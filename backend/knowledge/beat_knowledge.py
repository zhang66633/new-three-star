def get_beat_knowledge(node: str, beat_index: int) -> dict | None:
    """获取指定节点指定节拍的知识映射。"""
    node_knowledge = BEAT_KNOWLEDGE.get(node, {})
    return node_knowledge.get(beat_index, None)


def get_worldview_hook(node: str, beat_index: int) -> str:
    """获取指定节拍的世界观钩子。"""
    bk = get_beat_knowledge(node, beat_index)
    if bk:
        return bk.get("worldview_hook", "")
    return ""


def get_absurdity(node: str, beat_index: int) -> dict | None:
    """获取指定节拍的槽点指令。"""
    bk = get_beat_knowledge(node, beat_index)
    if bk:
        return bk.get("absurdity", None)
    return None


def get_mechanism_name(node: str, beat_index: int) -> str:
    """获取指定节拍的关联机制ID。"""
    bk = get_beat_knowledge(node, beat_index)
    if bk:
        return bk.get("mechanism_id", "")
    return ""