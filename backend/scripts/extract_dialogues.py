def clean_speaker(raw: str) -> str:
    """清洗说话人候选：去前导虚词、尾虚词，词典归一化"""
    s = raw
    # 去前导
    changed = True
    while changed:
        changed = False
        for l in LEAD:
            if s.startswith(l) and len(s) > len(l) + 1:
                s = s[len(l):]
                changed = True
                break
        # 单字虚词循环去
        if s and s[0] in ('却', '只', '便', '就', '又', '也', '还', '则', '即', '将', '正', '忙', '急', '连', '早', '尚', '竟', '忽', '猛', '才', '刚', '遂') and len(s) > 2:
            s = s[1:]
            changed = True
    # 去尾部"的"
    for t in TAIL:
        if s.endswith(t) and len(s) > len(t) + 1:
            s = s[:-len(t)]
    # 再查一次词典（如"曹操的"→"曹操"）
    if s in CHARACTERS:
        return s
    return s


def norm_speaker(raw: str) -> str:
    """归一化；无法确认的返回 ⚠+原样"""
    s = clean_speaker(raw)
    if not s:
        return '⚠未定'
    if s in CHARACTERS:
        return CHARACTERS[s]
    if s in TITLES:
        return s
    if s in NOT_SPEAKER:
        return '⚠未定'
    # 称谓后缀组合（如"老将军"）
    for suf in ['将军', '太守', '刺史', '州牧', '县令', '校尉', '军师', '丞相', '主公',
                '大人', '先生', '夫人', '太傅', '司徒', '太师', '大王', '王爷', '皇上',
                '陛下', '天子', '世子', '公子', '上将军', '老将军', '小将军', '大将军']:
        if s.endswith(suf) and len(s) > len(suf):
            base = s[:-len(suf)]
            if base in CHARACTERS:
                return CHARACTERS[base] + suf
            return s
    return '⚠' + s


def extract_chapter(fn: str):
    """用完整模式扫描单章"""
    with open(fn, encoding='utf-8') as f:
        content = f.read()
    page_m = re.match(r'# 第\d+章 .*?（原书页 (\d+)-(\d+)）', content)
    page_start, page_end = (int(page_m.group(1)), int(page_m.group(2))) if page_m else (0, 0)
    results = []
    for m in SPEECH_PAT.finditer(content):
        speaker_raw, quote = m.group(1), m.group(2)
        speaker = norm_speaker(speaker_raw)
        pos = m.start()
        ratio = pos / max(len(content), 1)
        page = page_start + int(ratio * (page_end - page_start + 1))
        results.append((page, speaker, quote))
    return results


