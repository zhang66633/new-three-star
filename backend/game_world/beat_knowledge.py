def get_beat_knowledge(node: str, beat_index: int) -> dict | None:
    """获取指定节点、节拍的预写知识。若无则返回 None。"""
    node_data = BEAT_KNOWLEDGE.get(node, {})
    return node_data.get(beat_index)


def get_worldview_hook(node: str, beat_index: int) -> str:
    """快捷获取本拍世界观钩子。"""
    k = get_beat_knowledge(node, beat_index)
    return k.get("worldview_hook", "") if k else ""


def get_absurdity(node: str, beat_index: int) -> dict | None:
    """快捷获取本拍槽点注入指令。"""
    k = get_beat_knowledge(node, beat_index)
    return k.get("absurdity") if k else None


def get_mechanism_name(mechanism_id: str) -> str:
    """获取机制名称。"""
    return MECHANISM_LOOKUP.get(mechanism_id, mechanism_id)
